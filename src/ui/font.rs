//! A tiny fixed-width bitmap font for the favourites launcher.
//!
//! No text-shaping library, no font file on disk — just a `const` table of 8x16
//! glyph bitmaps for printable ASCII (`0x20..=0x7E`), one bit per pixel, MSB-leftmost.
//! [`FONT_DATA`] was derived from Menlo (macOS's built-in monospace font) rendered at
//! 13pt with FreeType's monochrome hinting, not hand-typed — hand-typed glyph bytes are
//! the easy way to end up with legible-looking mush, so the generation script rasterised
//! real glyph outlines into the 8x16 cell instead of guessing pixels.
//!
//! Every drawing function here takes plain buffer/coordinate parameters
//! (`buf: &mut [u32]`, `buf_w`, `buf_h`) and touches nothing from `winit` or
//! `softbuffer` — that is what keeps this module unit-testable without a window.
//!
//! **Everything clips, nothing panics.** Negative coordinates, text that runs off any
//! edge, a zero-sized buffer, and a buffer shorter than `buf_w * buf_h` are all normal
//! inputs here (a window resize can produce every one of them mid-frame), so every pixel
//! write is bounds-checked before it happens.

/// Glyph cell width in pixels.
pub const CHAR_W: i32 = 8;
/// Glyph cell height in pixels.
pub const CHAR_H: i32 = 16;

/// One glyph bitmap: 16 rows, 8 bits each, MSB = leftmost pixel.
