/// Look up the glyph bitmap for `ch`, falling back to [`PLACEHOLDER`] for anything
/// outside `0x20..=0x7E`.
fn glyph_for(ch: char) -> &'static Glyph {
    let cp = ch as u32;
    if (0x20..=0x7E).contains(&cp) {
        &FONT_DATA[(cp - 0x20) as usize]
    } else {
        &PLACEHOLDER
    }
}

/// Write one pixel into `buf`, clipping silently against `buf_w`/`buf_h` and the
/// buffer's real length (which may be shorter than `buf_w * buf_h`, e.g. mid-resize).
#[inline]
